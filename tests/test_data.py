def test_safe_zip_is_extracted_read_only(tmp_path: Path) -> None:
    archive = tmp_path / "good.zip"
    with zipfile.ZipFile(archive, "w") as handle:
        handle.writestr("/", b"")
        handle.writestr("nested/value.txt", b"hello")
    item = fixture(archive, unpack="zip", members=2)
    layout = CacheLayout(tmp_path / "cache")
    layout.prepare()
    destination = layout.object_path(item.sha256)
    destination.parent.mkdir(parents=True)
    destination.write_bytes(archive.read_bytes())

    extracted = extract_object(layout, item)

    value = extracted / "nested" / "value.txt"
    assert value.read_bytes() == b"hello"
    assert value.stat().st_mode & 0o222 == 0


